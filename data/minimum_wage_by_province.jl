      : "Chart created by the Stone Centre on Wealth and Income Inequality<br>at the Vancouver School of Economics (UBC) using data from Employment and Social Development Canada";
    return {
      title: { text: "Provincial Minimum Wages" + (isReal ? " (Real, 2025 Dollars)" : "") },
      xaxis: { title: { text: "Year" } },
      yaxis: { title: { text: isReal ? "Hourly Minimum Wage (2025 \$ CAD)" : "Hourly Minimum Wage (Nominal \$ CAD)" } },
      showlegend: false,
      margin: { l: 60, b: MARGIN_B, r: 20, t: MARGIN_T },
      paper_bgcolor: "white",
      plot_bgcolor: "#E5ECF6",
      hovermode: "closest",
      annotations: [{
