  function monthKey(dateStr) { return dateStr.slice(0, 7); }

  // CPI for `geo` (a province name or "Canada") in the month containing
  // `dateStr`. Dates beyond the latest released month hold that month's
  // CPI constant.
  function cpiAt(geo, dateStr) {
    var series = CPI_MONTHLY[geo];
    var mk = monthKey(dateStr);
    if (series[mk] !== undefined) { return series[mk]; }
    var months = Object.keys(series).sort();
    return series[months[months.length - 1]];
  }

  // Average of each geography's twelve 2025 monthly CPI readings - the
  // "2025 dollars" reference level real values are expressed relative to.
  const REFERENCE_2025 = {};
  PROVINCES.concat(["Canada"]).forEach(function(geo) {
    var sum = 0;
    for (var m = 1; m <= 12; m++) {
      sum += CPI_MONTHLY[geo]["2025-" + (m < 10 ? "0" + m : m)];
    }
    REFERENCE_2025[geo] = sum / 12;
  });

  function realValue(nominal, geo, dateStr) {
    return nominal * REFERENCE_2025[geo] / cpiAt(geo, dateStr);
  }

  // Every first-of-month date from REAL_START through TODAY - the full set
  // of dates at which the deflator can change, independent of wage changes.
  function monthStartsBetween(start, end) {
    var out = [];
    var y = parseInt(start.slice(0, 4), 10), m = parseInt(start.slice(5, 7), 10);
    var endY = parseInt(end.slice(0, 4), 10), endM = parseInt(end.slice(5, 7), 10);
    while (y < endY || (y === endY && m <= endM)) {
      out.push(y + "-" + (m < 10 ? "0" + m : m) + "-01");
      m++;
      if (m > 12) { m = 1; y++; }
    }
    return out;
  }
  const MONTH_GRID = monthStartsBetween(REAL_START, TODAY);

  // A province's nominal series, resampled onto every date its real value
  // can change - each month start (deflator) union each date its own
  // statutory rate changes - and converted to 2025 dollars using its own
  // CPI. Cached since it never changes once computed.
  var realSeriesCache = {};
  function realSeries(prov) {
    if (realSeriesCache[prov]) { return realSeriesCache[prov]; }
    var raw = DATA[prov];
    var breakpoints = {};
    MONTH_GRID.forEach(function(d) { breakpoints[d] = true; });
    raw.dates.forEach(function(d) { if (d >= REAL_START && d <= TODAY) { breakpoints[d] = true; } });
    var dates = Object.keys(breakpoints).sort();
    var nominals = dates.map(function(d) { return stepValueAt(raw.dates, raw.rates, d); });
    var rates = dates.map(function(d, i) { return realValue(nominals[i], prov, d); });
    var result = { dates: dates, rates: rates, nominals: nominals };
    realSeriesCache[prov] = result;
    return result;
  }

  // Same idea for the Average line, but deflated with Canada's CPI (not
  // any province's), per the same rule computeAverageSeries follows for
  // nominal values.
  var realAverageSeriesCache = null;
  function realAverageSeries() {
    if (realAverageSeriesCache) { return realAverageSeriesCache; }
    var breakpoints = {};
    MONTH_GRID.forEach(function(d) { breakpoints[d] = true; });
    PROVINCES.forEach(function(p) {
      DATA[p].dates.forEach(function(d) { if (d >= REAL_START && d <= TODAY) { breakpoints[d] = true; } });
    });
    var dates = Object.keys(breakpoints).sort();
    var nominals = dates.map(function(d) {
      var vals = PROVINCES.map(function(p) { return stepValueAt(DATA[p].dates, DATA[p].rates, d); });
      return vals.reduce(function(a, b) { return a + b; }, 0) / vals.length;
    });
    var rates = nominals.map(function(nominal, i) { return realValue(nominal, "Canada", dates[i]); });
    realAverageSeriesCache = { dates: dates, rates: rates, nominals: nominals };
    return realAverageSeriesCache;
  }

  var MARGIN_T = 50, MARGIN_B = 130;

