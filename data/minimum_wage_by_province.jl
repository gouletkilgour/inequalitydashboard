#    is deflated using Canada's CPI, not any province's - see REFERENCE_2025
#    and realAverageSeries() in the generated page's JS.
#  - Statistics Canada does not publish province-level CPI before 1978-09;
#    this is the first month present for every province below (Canada's
#    series goes back much further, but is trimmed to match for consistency
#    with the constant REAL_START computed in JS from this data). The
#    real-dollar chart therefore starts in September 1978, later than the
#    nominal chart's 1974 start.
#  - The most recent month available as of the above download date is
#    2026-07; later dates (including "today") hold that month's CPI
