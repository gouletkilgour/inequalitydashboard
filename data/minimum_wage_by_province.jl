  // CPI_MONTHLY holds Statistics Canada's monthly, not-seasonally-adjusted
  // All-items CPI (Table 18-10-0004-01) for Canada and each province, from
  // the earliest month with complete province-level coverage (1978-09)
  // through the most recently released month. Every date's nominal wage is
  // deflated using the CPI for its own calendar month, so the real-dollar
  // line reflects inflation eroding the minimum wage between statutory
