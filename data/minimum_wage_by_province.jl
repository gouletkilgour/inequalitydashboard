  // Earliest month with CPI data for every one of the ten provinces (the
  // same "latest of the ten start dates" logic DISPLAY_START uses above).
  const REAL_START = PROVINCES.map(function(p) {
    return Object.keys(CPI_MONTHLY[p]).sort()[0] + "-01";
